"""Feed vetter stage A (offline): turn curated feed lists into FeedCandidates.

Input files share one shape::

    'United States':
      nytimes.com:
        rank: 69
        languages: [en]
        avg_article_length: 1026
        name: The New York Times      # optional (supplement only)
        notes: ...                    # optional (supplement only)
        feeds:
          'Politics & Society':
            - 'https://...'

Categories prefixed ``Podcasts: `` become ``medium=audio`` with the prefix
stripped. Domains whose listed languages exclude English are dropped. The same
feed URL listed more than once is merged into one candidate whose categories
are the union, in first-seen order.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from newsrag import ids
from newsrag.contracts.v1 import FeedCandidate, FeedMedium, FeedOrigin

PODCAST_PREFIX = "Podcasts: "
DEFAULT_EXCLUDED_CATEGORIES = frozenset({"Other"})

_Loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
_Dumper = getattr(yaml, "CSafeDumper", yaml.SafeDumper)


@dataclass
class ExtractStats:
    domains_seen: int = 0
    domains_non_english: int = 0
    feeds_seen: int = 0
    feeds_invalid_url: int = 0
    feeds_excluded_category: int = 0
    feeds_merged_duplicate: int = 0
    by_medium: Counter[str] = field(default_factory=Counter)
    by_category: Counter[str] = field(default_factory=Counter)


def load_yaml(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return yaml.load(f, Loader=_Loader)


def extract_candidates(
    sources: Iterable[tuple[Mapping[str, Any], FeedOrigin]],
    country: str = "United States",
    excluded_categories: frozenset[str] = DEFAULT_EXCLUDED_CATEGORIES,
) -> tuple[list[FeedCandidate], ExtractStats]:
    stats = ExtractStats()
    by_id: dict[str, dict[str, Any]] = {}

    for data, origin in sources:
        for domain, info in (data.get(country) or {}).items():
            stats.domains_seen += 1
            info = info or {}
            languages = [str(x) for x in info.get("languages") or []]
            if languages and "en" not in languages:
                stats.domains_non_english += 1
                continue
            for raw_category, urls in (info.get("feeds") or {}).items():
                category = str(raw_category)
                medium = FeedMedium.TEXT
                if category.startswith(PODCAST_PREFIX):
                    medium = FeedMedium.AUDIO
                    category = category.removeprefix(PODCAST_PREFIX)
                for url in urls or []:
                    stats.feeds_seen += 1
                    if category in excluded_categories:
                        stats.feeds_excluded_category += 1
                        continue
                    try:
                        normalized = ids.normalize_url(str(url))
                    except ids.InvalidURL:
                        stats.feeds_invalid_url += 1
                        continue
                    fid = ids.feed_id(normalized)
                    if fid in by_id:
                        stats.feeds_merged_duplicate += 1
                        cats = by_id[fid]["categories"]
                        if category not in cats:
                            cats.append(category)
                        continue
                    by_id[fid] = {
                        "feed_id": fid,
                        "feed_url": normalized,
                        "source_id": ids.registered_domain(str(domain)),
                        "listed_domain": str(domain),
                        "country": country,
                        "categories": [category],
                        "medium": medium,
                        "origin": origin,
                        "listed_languages": languages,
                        "listed_rank": info.get("rank"),
                        "listed_avg_article_length": info.get("avg_article_length"),
                        "display_name": info.get("name"),
                        "notes": info.get("notes"),
                    }

    candidates = sorted(
        (FeedCandidate.model_validate(v) for v in by_id.values()),
        key=lambda c: (c.source_id, c.feed_url),
    )
    for c in candidates:
        stats.by_medium[c.medium.value] += 1
        stats.by_category[c.categories[0]] += 1
    return candidates, stats


def write_candidates(candidates: list[FeedCandidate], path: Path) -> None:
    rows = [c.model_dump(mode="json", exclude_none=True) for c in candidates]
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# GENERATED by `newsrag feeds candidates`. Do not edit by hand:\n"
        "# edit feeds/supplement_us.yaml or the source list and regenerate.\n"
    )
    with path.open("w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        yaml.dump(rows, f, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)
